# 借鉴 MaiBot 的 multiple_reply_style：低概率抽一个一次性语调。
# 同一套人设连说几十轮会自己收敛成一个平均值，偶尔的偏移是最便宜的解法。
TONE_VARIANTS = [
    '这一轮你懒得组织长句，用很短的话接就行。',
    '这一轮你有点想逗他，接话时可以故意曲解一下。',
    '这一轮你话比平时多一点，可以顺手多讲一个刚想到的细节。',
    '这一轮你有点走神，反应慢半拍，可能先「啊」一声才接上。',
    '这一轮你懒散得很，语气拖一点，句尾松一点。',
    '这一轮你莫名有点较真，会为一个细节多问一句。',
]

TONE_PROBABILITY = 0.25


def pick_tone(rng: Optional[random.Random] = None, probability: float = TONE_PROBABILITY) -> Optional[str]:
    """按概率抽一个只影响这一轮的语调。没抽中返回 None。"""

    if probability <= 0 or not TONE_VARIANTS:
        return None
    picker = rng or random
    if picker.random() > probability:
        return None
    return picker.choice(TONE_VARIANTS)


