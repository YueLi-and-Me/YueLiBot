# 名称 → 编号。重名取先出现的小黄脸编号；表本身有序，因此结果稳定。
_FACE_IDS: Dict[str, str] = {}
for _face_id, _name in FACE_NAMES.items():
    _FACE_IDS.setdefault(_name, _face_id)


def face_id_by_name(name: str) -> str:
    """按 QQ 表情名反查编号。

    :param name: QQ 表情名，必须与平台表里的名称逐字一致。
    :return: 对应的表情编号字符串。
    :raises KeyError: 名称不在表内。不做近似匹配：贴错表情不会报错、只会显示成
        另一个表情，是最难发现的那类错，因此名字对不上必须当场炸掉。
    """
    return _FACE_IDS[name]


def face_name(face_id: str) -> str | None:
    """按编号取表情名，未知编号返回 ``None``。

    :param face_id: 消息段里的表情编号。
    :return: 表情名；表里没有该编号时返回 ``None``，由调用方决定如何降级展示。
    """
    return FACE_NAMES.get(face_id)
